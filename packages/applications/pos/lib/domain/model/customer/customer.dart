class Customer {
  final String id;
  final String code;
  final String name;
  final String address;
  final String phone;
  final String email;
  final String status;

  Customer({
    required this.id,
    required this.code,
    required this.name,
    required this.address,
    required this.phone,
    required this.email,
    required this.status,
  });
}
